def run_cmd(args, cwd=WORKSPACE_DIR):
    cmd = [sys.executable, "-m", "textora_engine"] + args
    res = subprocess.run(
        cmd,
        cwd=cwd,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    return res


YT_BLOCK_MARKERS = (
    "rate limited",
    "ipblocked",
    "requestblocked",
    "too many requests",
    "429",
    "no captions available",
    "youtube video unavailable",
    "connection refused",
    "failed to fetch captions",
)


def youtube_was_blocked(stdout: str, stderr: str = "") -> bool:
    """Detect whether Textora correctly caught a YouTube IP-block/rate-limit."""
    combined = (stdout + stderr).lower()
    return any(marker in combined for marker in YT_BLOCK_MARKERS)


def make_fallback_local_video(parent_dir: Path, name: str, caption_text: str) -> Path:
    """Create a local .mp4 stub with a sibling SRT so the pipeline processes it."""
    vid = parent_dir / f"{name}.mp4"
    srt = parent_dir / f"{name}.srt"
    vid.write_bytes(b"\x00\x00\x00\x18ftypmp42" + b"\x00" * 200)
    srt.write_text(
        f"1\n00:00:00,000 --> 00:00:04,000\n{caption_text}\n\n"
        "2\n00:00:04,500 --> 00:00:08,000\nThis transcript was generated by Textora Engine for CI fallback verification.\n",
        encoding="utf-8",
    )
    return vid


def assert_pure_txt(txt_path: Path) -> None:
    """Strict pure-text assertion: no headers, no timestamps, no metadata."""
    content = txt_path.read_text(encoding="utf-8")
    assert len(content) > 10, f"Transcript at {txt_path} is too short"
    for line in content.splitlines()[:5]:
        assert not line.startswith("#"), f"Found header in text: {line}"
        assert "-->" not in line, f"Found timestamp in text: {line}"
        assert "Title:" not in line, f"Found metadata in text: {line}"


